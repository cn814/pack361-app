/** What a scout did to earn this adventure, or null if we don't have words for it. */
export function awardBlurb(rank: DenRank | null, adventure: string | null): string | null {
  if (!adventure) return null;
  const key = adventure.trim().toLowerCase().replace(/[’‘]/g, "'");
  return (rank ? BY_RANK[rank]?.[key] : undefined) ?? ANY_RANK[key] ?? null;
}

/** Every adventure the cheat sheet has words for, for the tests. */
export const BLURB_KEYS = Object.entries(BY_RANK).flatMap(([rank, m]) => Object.keys(m).map((k) => `${rank}|${k}`));
